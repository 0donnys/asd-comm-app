def shade(cell, color='EFE8DA'):
    tcPr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement('w:shd')
    shd.set(qn('w:fill'), color)
    tcPr.append(shd)


def table(headers, rows, widths, font_size=11.5):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = 'Table Grid'
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.autofit = False
    hdr = t.rows[0]
    hdr._tr.get_or_add_trPr().append(OxmlElement('w:tblHeader'))
    for i, h in enumerate(headers):
        cell = hdr.cells[i]
        cell.width = widths[i]
        cell.vertical_alignment = WD_ALIGN_VERTICAL.CENTER
        par = cell.paragraphs[0]
        par.alignment = WD_ALIGN_PARAGRAPH.CENTER
        par.paragraph_format.first_line_indent = Cm(0)
        par.paragraph_format.line_spacing = 1.0
        par.paragraph_format.space_after = Pt(0)
        r = par.add_run(h)
        set_font(r, font_size, True)
        shade(cell)
    for row in rows:
        tr = t.add_row()
        tr._tr.get_or_add_trPr().append(OxmlElement('w:cantSplit'))
        for i, val in enumerate(row):
            cell = tr.cells[i]
            cell.width = widths[i]
            cell.vertical_alignment = WD_ALIGN_VERTICAL.CENTER
            par = cell.paragraphs[0]
            par.alignment = WD_ALIGN_PARAGRAPH.LEFT
            par.paragraph_format.first_line_indent = Cm(0)
            par.paragraph_format.line_spacing = 1.0
            par.paragraph_format.space_after = Pt(0)
            r = par.add_run(str(val))
            set_font(r, font_size, False)
    p('', first=Cm(0), after=0, line=1.0)


