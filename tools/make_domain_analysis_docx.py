def p(text='', align=WD_ALIGN_PARAGRAPH.JUSTIFY, first=Cm(1.25), left=Cm(0),
      bold=False, size=14, before=0, after=0, line=1.5, keep=False):
    par = doc.add_paragraph()
    pf = par.paragraph_format
    pf.alignment = align
    pf.first_line_indent = first
    pf.left_indent = left
    pf.space_before = Pt(before)
    pf.space_after = Pt(after)
    pf.line_spacing = line
    pf.keep_with_next = keep
    if text:
        r = par.add_run(text)
        set_font(r, size, bold)
    return par


